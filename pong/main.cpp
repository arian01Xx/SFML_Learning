struct Player1{
    int y=2;
    int start_x;
    int paddle_height=3;
    sf::RectangleShape player;

    Player1(){
        player.setSize(sf::Vector2f(TILE-2.f, TILE-2.f));
        player.setPosition(sf::Vector2f(50.f, 50.f));
        player.setFillColor(sf::Color::Red);
    }

    void init(World** _world){
        start_x=((*_world)->row/2)-(paddle_height/2);
    }

    void handleInput(World** _world){
        if(sf::Keyboard::isKeyPressed(sf::Keyboard::Key::W)) start_x--;
        if(sf::Keyboard::isKeyPressed(sf::Keyboard::Key::S)) start_x++;

        //LIMITES
        if(start_x<1) start_x=1;
        if(start_x+paddle_height>=(*_world)->row-1)
            start_x=((*_world)->row-1)-paddle_height;
    }

    void draw(sf::RenderWindow& window, World** _world){
        for(int i=0; i<paddle_height; i++){
            player.setPosition({float(y*TILE), float((start_x+i)*TILE)});
            window.draw(player);
        }
    }
};

struct Player2: Player1{

};

void execute(){

    World* _world=new World;
    Player1* _player1=new Player1;

    _player1->init(&_world); //inicializa posicion seguro

    sf::RenderWindow window{
        sf::VideoMode({
            static_cast<unsigned>(_world->col*TILE),
            static_cast<unsigned>(_world->row*TILE)
            }), 
        "SFML works!"
    };

    while(window.isOpen()){
        while(const std::optional event=window.pollEvent()){
            if(event->is <sf::Event::Closed>()) window.close();
        }
        //ZONA INPUT
        _player1->handleInput(&_world);

        //ZONA DE GRAFICAS
        window.clear();
        _world->draw(window);
        _player1->draw(window, &_world);
        window.display();
        
    }
}

int main(){
    execute();
    return 0;
}

